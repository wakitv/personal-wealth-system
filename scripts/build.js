#!/usr/bin/env node
/**
 * Keeps ONE copy of the financial logic. shared/*.js is the source; this script
 * copies it into the Apps Script project and the frontend. `--check` fails if any
 * copy has drifted (run by `npm test`).
 */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const targets = [
  ['shared/core.js', 'backend/Core.gs'],
  ['shared/service.js', 'backend/Service.gs'],
  ['shared/core.js', 'frontend/js/shared/core.js'],
  ['shared/service.js', 'frontend/js/shared/service.js']
];
const banner = (src) => `// GENERATED from ${src} by scripts/build.js — edit the source, then run \`npm run build\`.\n`;
const check = process.argv.includes('--check');
let drift = 0;
for (const [src, dst] of targets) {
  const want = banner(src) + fs.readFileSync(path.join(root, src), 'utf8');
  const dstPath = path.join(root, dst);
  if (check) {
    const have = fs.existsSync(dstPath) ? fs.readFileSync(dstPath, 'utf8') : '';
    if (have !== want) { console.error(`✗ ${dst} is out of date with ${src} (run npm run build)`); drift++; }
  } else {
    fs.mkdirSync(path.dirname(dstPath), { recursive: true });
    fs.writeFileSync(dstPath, want);
    console.log(`✓ ${src} → ${dst}`);
  }
}
// One-file Apps Script bundle: paste a single file into the Apps Script editor.
{
  const order = ['Core.gs', 'Service.gs', 'Config.gs', 'Auth.gs', 'SheetStore.gs', 'Code.gs', 'Setup.gs', 'Snapshots.gs'];
  const read = (f) => (f === 'Core.gs' ? banner('shared/core.js') + fs.readFileSync(path.join(root, 'shared/core.js'), 'utf8')
    : f === 'Service.gs' ? banner('shared/service.js') + fs.readFileSync(path.join(root, 'shared/service.js'), 'utf8')
    : fs.readFileSync(path.join(root, 'backend', f), 'utf8'));
  const want = '/**\n * Personal Wealth OS — Apps Script backend, ALL-IN-ONE FILE.\n * GENERATED by scripts/build.js from backend/*.gs and shared/*.js. Paste this whole file\n * into the Apps Script editor as Code.gs (replacing its contents). Do not edit by hand.\n */\n\n' +
    order.map((f) => '// ===== ' + f + ' =====\n' + read(f)).join('\n\n');
  const dst = 'backend/single-file/Code.gs', dstPath = path.join(root, dst);
  if (check) {
    const have = fs.existsSync(dstPath) ? fs.readFileSync(dstPath, 'utf8') : '';
    if (have !== want) { console.error(`✗ ${dst} is out of date (run npm run build)`); drift++; }
  } else { fs.mkdirSync(path.dirname(dstPath), { recursive: true }); fs.writeFileSync(dstPath, want); console.log(`✓ backend/*.gs → ${dst}`); }
}

if (check) {
  if (drift) process.exit(1);
  console.log('✓ shared logic is in sync across backend and frontend');
}
